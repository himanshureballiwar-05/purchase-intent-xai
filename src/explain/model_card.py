"""Generate ``docs/model_card.md`` from training results (always in sync with the model)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def write_model_card(meta: dict[str, Any], comparison: pd.DataFrame, path: str | Path) -> Path:
    """Write the model card (intended use, data, metrics, limitations)."""
    t = meta["test_metrics_at_threshold"]
    d = meta["test_metrics_at_0.5"]
    b = meta["baseline"]
    v = meta["net_value_on_test"]
    abl = meta.get("ablation_page_values")
    best = comparison.sort_values("pr_auc", ascending=False).drop_duplicates("model")
    table = "\n".join(
        f"| {r.model} | {r.strategy} | {r.pr_auc:.3f} | {r.roc_auc:.3f} | {r.recall:.3f} | {r.precision:.3f} | {'yes' if r.tuned else 'no'} |"
        for r in best.itertuples()
    )
    feats = "\n".join(
        f"- **{f['feature']}** (mean |SHAP| = {f['mean_abs_shap']:.3f})"
        for f in meta["top_features"][:6]
    )
    abl_txt = (
        f"Without `PageValues` the cross-validated PR-AUC is **{abl['cv_pr_auc']:.3f}** "
        f"(test recall {_pct(abl['test']['recall'])}), compared with **{meta['cv_metrics']['pr_auc']:.3f}** with it."
        if abl
        else "Ablation not run (model already trained without PageValues)."
    )
    text = f"""# Model Card - Purchase Intent Classifier

*Auto-generated by `src/models/train.py` on {meta['trained_at']} (do not edit by hand).*

## Model details
- **Algorithm:** {meta['model_name']} (tuned: {meta['tuned']})
- **Imbalance strategy:** {meta['strategy']}
- **Decision threshold:** {meta['threshold']:.2f} ({meta['threshold_method']})
- **Uses PageValues:** {meta['use_page_values']}
- **Library versions:** Python {meta['python']}, scikit-learn {meta['sklearn']}; seed {meta['seed']}

## Intended use
Score live e-commerce sessions by probability of purchase so the business can trigger
a targeted intervention (discount nudge, free-shipping banner, chat prompt) for
*undecided* visitors. It supports decisions; it does not make decisions about
individuals' access to goods or prices.

## Training data
`dataset/ecommerce_sessions.csv`: {meta['n_train'] + meta['n_test']:,} sessions, 17 behaviour features, binary target `Converted`
(positive rate {_pct(meta['positive_rate'])}). Stratified 80/20 split ({meta['n_train']:,} train / {meta['n_test']:,} test).

## Performance (held-out test set)
| Metric | At default 0.5 | At chosen threshold {meta['threshold']:.2f} |
|---|---|---|
| PR-AUC | {d['pr_auc']:.3f} | {t['pr_auc']:.3f} |
| ROC-AUC | {d['roc_auc']:.3f} | {t['roc_auc']:.3f} |
| Recall | {d['recall']:.3f} | {t['recall']:.3f} |
| Precision | {d['precision']:.3f} | {t['precision']:.3f} |
| F1 | {d['f1']:.3f} | {t['f1']:.3f} |
| Accuracy | {d['accuracy']:.3f} | {t['accuracy']:.3f} |

*Baseline "nobody buys":* accuracy {_pct(b['accuracy'])} but recall 0%, so **accuracy alone is misleading**.

Confusion matrix at the chosen threshold: TN={t['tn']}, FP={t['fp']}, FN={t['fn']}, TP={t['tp']}.

### Model comparison (5-fold CV on train, best strategy per model)
| Model | Strategy | PR-AUC | ROC-AUC | Recall | Precision | Tuned |
|---|---|---|---|---|---|---|
{table}

## Business value (illustrative assumptions in `config.yaml`)
Value per saved purchase {meta['business_case']['value_per_conversion']}, nudge cost {meta['business_case']['intervention_cost']},
nudge success rate {_pct(meta['business_case']['success_rate'])} -> break-even probability **{meta['break_even_probability']:.2f}**.
Expected net value on the test set: chosen threshold **{v['chosen_threshold']:.0f}**, default 0.5 **{v['default_0.5']:.0f}**,
nudge everyone **{v['flag_everyone']:.0f}**, nudge nobody **0**.

## Explainability
Top global drivers (SHAP):
{feats}

## The PageValues question (leakage review)
`PageValues` is the most predictive feature but is recorded close to the checkout step, so it may not be available
early in a session. {abl_txt}
Set `features.use_page_values: false` in `config.yaml` (or train with `--no-page-values`) for an early-scoring variant.

## Limitations & ethical considerations
- Trained on one dataset snapshot; behaviour, seasonality and traffic mix drift over time. Re-train and monitor.
- `Month` and `SpecialDay` encode seasonality; they may not generalise to unseen months.
- Probabilities are model scores, not guarantees; low-confidence predictions near the threshold should not trigger costly actions.
- No personal identifiers are used. `Region`, `Browser` and `OperatingSystems` should be reviewed for proxy bias before any price- or access-related use.
- Business-value numbers are assumptions, not measured results.
"""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path
